        guard let v = DataMarketCatalog.vendorByID[id] else { return "Unknown vendor." }
        if tier > 0 && s.year < v.available { return "Not available until \(Int(v.available))." }
        s.dataEco.annotation.removeAll { $0.id == id }
        if tier > 0 { s.dataEco.annotation.append(AnnotationContract(id: id, tier: clamp(tier, 1, 3), started: s.date)) }
