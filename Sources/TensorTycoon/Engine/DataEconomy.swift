    static func setDetection(_ s: inout GameState, _ level: Int) -> String? {
        let l = clamp(level, 0, 3)
        if l == 3 && !s.researched.contains("decontamination") { return "Research Benchmark Decontamination first." }
        if l > s.dataEco.detection {
            let cost = detectionLevels[l].setup - detectionLevels[s.dataEco.detection].setup
            if cost > s.cash { return "Setting it up costs \(Fmt.money(cost))." }
            pay(&s, cost)
        }
        s.dataEco.detection = l
        return nil
    }

    // MARK: Rivals

    /// A rival lab's access to the world's training data (0–1): bigger labs buy more. For display and the c effect.
    static func rivalBaseAccess(_ s: GameState, _ lab: String) -> Double {
        let def = CompetitorCatalog.def(lab)
        return clamp(0.35 + 0.6 * min(1, def.computeShare / 0.25) + 0.1 * (RivalIntel.unit("data|access|\(lab)") - 0.5), 0.2, 0.97)
    }

    /// Capability (log10) a rival loses to your exclusives and gains from rare data it won. Small on purpose:
    /// at most −0.05 and +0.04.
    static func rivalC(_ s: GameState, _ lab: String) -> Double {
        let e = s.dataEco
        guard !e.holdings.isEmpty || !e.rivalGains.isEmpty else { return 0 }
        let access = rivalBaseAccess(s, lab)
        let lost = e.holdings.filter { $0.exclusive && $0.active }.reduce(0) { $0 + (DataMarketCatalog.byID[$1.source]?.rivalValue ?? 0) }
        let won = (e.rivalGains[lab] ?? []).reduce(0) { $0 + (DataMarketCatalog.byID[$1]?.rivalValue ?? 0) }
        return min(0.04, won) - min(0.05, lost * access)
    }

    /// Displayed access level after your exclusives.
    static func rivalAccess(_ s: GameState, _ lab: String) -> Double {
        let lost = s.dataEco.holdings.filter { $0.exclusive && $0.active }.reduce(0) { $0 + (DataMarketCatalog.byID[$1.source]?.rivalValue ?? 0) }
        let won = (s.dataEco.rivalGains[lab] ?? []).reduce(0) { $0 + (DataMarketCatalog.byID[$1]?.rivalValue ?? 0) }
        return clamp(rivalBaseAccess(s, lab) * (1 - 4 * lost) + 3 * won, 0, 1)
    }

    // MARK: Daily

    static func roll(_ s: GameState, _ tag: String) -> Double { RivalIntel.unit("data|\(s.lifecycleSalt)|\(tag)") }

    static func daily(_ s: inout GameState) {
        let today = s.date
        // Processing jobs
        if !s.dataEco.jobs.isEmpty {
            for j in s.dataEco.jobs where j.done <= today { finish(&s, j) }
            s.dataEco.jobs.removeAll { $0.done <= today }
        }
        // Synthetic generation
        if !s.dataEco.synth.isEmpty {
            for j in s.dataEco.synth where j.done <= today {
                let h = synthHolding(j, date: today)
                s.dataEco.holdings.append(h)
                Sim.news(&s, "Synthetic data ready: \(Fmt.tokens(j.tokensT))", "\(j.modelName) generated \(j.focus.label.lowercased()) data at quality \(Int(h.quality.effective * 100)). Keep synthetic data under ~20% of your corpus to avoid model collapse.",
                         .research, good: true)
            }
            s.dataEco.synth.removeAll { $0.done <= today }
        }
        // Annotation output
        for c in s.dataEco.annotation {
            guard let v = DataMarketCatalog.vendorByID[c.id] else { continue }
            let add = v.throughputT * throughputMult(c.tier) / 30.4
            let hid = "an:" + v.id
            if let i = s.dataEco.holdings.firstIndex(where: { $0.id == hid }) {
                s.dataEco.holdings[i].tokensT += add
                s.dataEco.holdings[i].refreshed = today
                s.dataEco.holdings[i].active = true
            } else {
                s.dataEco.holdings.append(DataHolding(id: hid, name: "\(v.name) output", kind: v.kind, focus: v.focus, source: v.id, tokensT: add,
                                                      quality: v.quality, term: .buy, acquired: today, refreshed: today))
            }
        }
        // Licence expiry
        for i in s.dataEco.holdings.indices where s.dataEco.holdings[i].active {
            if let e = s.dataEco.holdings[i].expires, e <= today {
                s.dataEco.holdings[i].active = false
                s.dataEco.holdings[i].monthly = 0
                Sim.news(&s, "Licence expired: \(s.dataEco.holdings[i].name)", "New runs can't use it. Renew it on the Training Data page.", .company, good: false)
            }
        }
        // Expired data no run uses any more is dropped.
        if s.dataEco.holdings.contains(where: { !$0.active }) {
            let keep = s.dataEco.holdings.filter { $0.active || inUse(s, $0.id) }
            if keep.count != s.dataEco.holdings.count { s.dataEco.holdings = keep }
        }
        let day = GameCalendar.components(today).day
        if day == 1 { monthly(&s) }
        if day == 11 { offers(&s) }
    }

    static func finish(_ s: inout GameState, _ j: DataJob) {
        s.dataEco.applied[j.target, default: []].append(j.stage.rawValue)
        if let i = s.dataEco.holdings.firstIndex(where: { $0.id == j.target }) {
            var q = s.dataEco.holdings[i].quality, t = s.dataEco.holdings[i].tokensT
            apply(j.stage, to: &q, tokensT: &t, holding: true)
            s.dataEco.holdings[i].quality = q
            s.dataEco.holdings[i].tokensT = t
        } else if DataCatalog.byID[j.target] != nil {
            var q = s.dataEco.processed[j.target] ?? DataMarketCatalog.legacyProfile(j.target).quality, t = 0.0
            apply(j.stage, to: &q, tokensT: &t, holding: false)
            s.dataEco.processed[j.target] = q
        } else { return }
        Sim.news(&s, "Data pipeline: \(j.name) — \(j.stage.label.lowercased()) done", j.stage.detail, .research, good: true)
    }

    static func monthly(_ s: inout GameState) {
        // Partnerships and live licences keep data fresh; partners publish more.
        for i in s.dataEco.holdings.indices where s.dataEco.holdings[i].active {
            switch s.dataEco.holdings[i].term {
            case .partnership:
                s.dataEco.holdings[i].refreshed = s.date
                s.dataEco.holdings[i].tokensT *= 1.01
            case .licence:
                s.dataEco.holdings[i].refreshed = s.date
            default: break
            }
        }
        lawsuits(&s)
    }

    // MARK: Lawsuits

    static func lawsuits(_ s: inout GameState) {
        let y = s.year
        let ym = s.date.ym
        for h in s.dataEco.holdings where h.quality.provenance < 0.5 && !s.dataEco.sued.contains(h.id) {
            let law = s.lawsPassed.contains("copyright") ? 1.5 : 1
            let p = 0.06 * (0.5 - h.quality.provenance) / 0.5 * s.market.copyrightHeat * law * (y < 2023 ? 0.3 : 1)
            guard roll(s, "suit|\(h.id)|\(ym.year)-\(ym.month)") < p else { continue }
            s.dataEco.sued.insert(h.id)
            let base = max(3_000_000, h.value * 3, Economy.runRate(s) * 0.02)
            let fine = clamp(base * s.market.copyrightHeat * law, 2e6, 8e8) * Policy.fineFactor(s)
            let who = h.kind == .code ? "Open-source developers" : (h.kind == .images ? "Photographers and artists" : "Rights holders")
            Events.addDecision(&s, kind: "data_lawsuit", title: "\(who) sue over \(h.name)",
                               body: "A suit says the data was taken without permission (provenance \(Int(h.quality.provenance * 100))/100)\(law > 1 ? ", and the new copyright law is on their side" : ""). Lawyers estimate \(Fmt.money(fine)) to settle.",
                               image: "stock_exchange",
                               options: [DecisionOption(label: "Settle (\(Fmt.money(fine)))", detail: "Pay and keep using the data."),
                                         DecisionOption(label: "Settle and purge it (\(Fmt.money(fine * 0.6)))", detail: "Pay less and delete the dataset from future runs."),
                                         DecisionOption(label: "Fight in court", detail: "About even odds; lose and pay double, brand −4.")],
                               amount: fine, ref: h.id)
            return
        }
    }

    // MARK: Rare collections and auctions

    static func offers(_ s: inout GameState) {
        let y = s.year
        guard y >= 2018, !s.decisions.contains(where: { $0.kind == "data_auction" || $0.kind == "data_collection" }) else { return }
        if let last = s.dataEco.lastOffer, GameCalendar.daysBetween(last, s.date) < 180 { return }
        let ym = s.date.ym
        guard roll(s, "offer|\(ym.year)-\(ym.month)") < 0.12 else { return }
        let pool = DataMarketCatalog.rare.filter { y >= $0.available && !s.dataEco.offered.contains($0.id) }
        guard !pool.isEmpty else { return }
        let def = pool[Int(roll(s, "which|\(ym.year)-\(ym.month)") * Double(pool.count)) % pool.count]
        s.dataEco.offered.insert(def.id)
        s.dataEco.lastOffer = s.date
        let reserve = def.price
        let bidders = rivalBidders(s, def)
        if roll(s, "kind|\(def.id)") < 0.65 && !bidders.isEmpty {
            let names = bidders.map { CompetitorCatalog.def($0).name }
            let heat = roll(s, "heat|\(def.id)")
            Events.addDecision(&s, kind: "data_auction", title: "Auction: \(def.name)",
                               body: "\(def.seller.capitalizedFirst) is auctioning \(def.name.lowercased()) (\(Fmt.tokens(def.tokensT)), quality \(Int(def.quality.effective * 100))). \(def.blurb) Sealed bids, highest wins exclusive rights. Also bidding: \(names.joined(separator: ", ")) — interest looks \(heat > 0.6 ? "fierce" : (heat > 0.3 ? "keen" : "modest")).",
                               image: "stock_exchange",
                               options: [DecisionOption(label: "Bid the reserve (\(Fmt.money(reserve)))", detail: "Wins only if rivals bid low. You pay just above the best rival bid."),
                                         DecisionOption(label: "Bid high (\(Fmt.money(reserve * 1.6)))", detail: "Likely wins. You pay just above the best rival bid."),
                                         DecisionOption(label: "Pass", detail: "A rival takes it and its next models get a little better.")],
                               amount: reserve, ref: def.id)
        } else {
            Events.addDecision(&s, kind: "data_collection", title: "Private sale: \(def.name)",
                               body: "\(def.seller.capitalizedFirst) offers you \(def.name.lowercased()) privately before going wider (\(Fmt.tokens(def.tokensT)), quality \(Int(def.quality.effective * 100))). \(def.blurb)",
                               image: "stock_exchange",
                               options: [DecisionOption(label: "Buy it (\(Fmt.money(reserve)))", detail: "Exclusive: no rival lab gets it."),
                                         DecisionOption(label: "Pass", detail: "It goes to the next lab on their list.")],
                               amount: reserve, ref: def.id)
        }
    }

    /// The rival labs bidding for a rare dataset: the biggest active labs, picked by hash.
    static func rivalBidders(_ s: GameState, _ def: DatasetDef) -> [String] {
        let labs = s.competitors.filter { !$0.acquired && !$0.bankrupt && $0.exitNote.isEmpty }.map(\.id)
            .sorted { CompetitorCatalog.def($0).computeShare > CompetitorCatalog.def($1).computeShare }
        return Array(labs.prefix(5).filter { roll(s, "bid|\(def.id)|\($0)") < 0.6 }.prefix(3))
    }

    static func resolve(_ s: inout GameState, _ d: Decision, option: Int) {
        switch d.kind {
        case "data_auction":
            guard let def = DataMarketCatalog.byID[d.ref] else { return }
            let bidders = rivalBidders(s, def)
            let top = def.price * (0.85 + 0.8 * roll(s, "heat|\(def.id)"))
            let winner = bidders.max { roll(s, "bid|\(def.id)|\($0)") < roll(s, "bid|\(def.id)|\($1)") }
            let mine = option == 0 ? def.price : (option == 1 ? def.price * 1.6 : 0)
            let paid = max(def.price, min(mine, top * 1.02))
            if mine > 0 && mine >= top && paid <= s.cash {
                win(&s, def, paid: paid)
                s.dataEco.auctionsWon += 1
                Sim.news(&s, "You won the auction for \(def.name)", "Paid \(Fmt.money(paid)); the best rival bid was \(Fmt.money(top)). It's yours alone.", .company, good: true)
            } else {
                if mine > 0 { s.dataEco.auctionsLost += 1 }
                if let w = winner { rivalWins(&s, def, lab: w, price: top) }
            }
        case "data_collection":
            guard let def = DataMarketCatalog.byID[d.ref] else { return }
            if option == 0 && def.price <= s.cash {
                win(&s, def, paid: def.price)
                Sim.news(&s, "Bought: \(def.name)", "\(Fmt.money(def.price)), exclusively yours.", .company, good: true)
            } else if let w = rivalBidders(s, def).first {
                rivalWins(&s, def, lab: w, price: def.price)
            }
        case "data_lawsuit":
            let fine = d.amount
            switch option {
            case 0:
                pay(&s, fine)
                s.dataEco.settlements += fine
                Sim.news(&s, "Data lawsuit settled for \(Fmt.money(fine))", "You keep the data. Next time, check provenance before you buy.", .policy, good: false)
            case 1:
                pay(&s, fine * 0.6)
                s.dataEco.settlements += fine * 0.6
                if let i = s.dataEco.holdings.firstIndex(where: { $0.id == d.ref }) {
                    s.dataEco.holdings[i].active = false
                    s.dataEco.holdings[i].monthly = 0
                }
                Sim.news(&s, "Data lawsuit settled; dataset purged", "Paid \(Fmt.money(fine * 0.6)) and deleted the data from future runs.", .policy)
            default:
                if roll(s, "court|\(d.ref)") < 0.5 {
                    pay(&s, fine * 0.1)
                    Sim.news(&s, "You won the data lawsuit", "The court found the use transformative. Legal fees: \(Fmt.money(fine * 0.1)).", .policy, good: true)
                } else {
                    pay(&s, fine * 2)
                    s.dataEco.settlements += fine * 2
                    s.brand = max(0, s.brand - 4)
                    Sim.news(&s, "You lost the data lawsuit", "Damages of \(Fmt.money(fine * 2)). Brand −4.", .policy, important: true, good: false)
                }
            }
        default: break
        }
    }

    static func win(_ s: inout GameState, _ def: DatasetDef, paid: Double) {
        let transfer = def.tokensT * def.kind.bytesPerToken * transferPerTB(s.year)
        pay(&s, paid + transfer)
        var h = DataHolding(id: holdingID(def), name: def.name, kind: def.kind, focus: def.focus, source: def.id, tokensT: def.tokensT,
                            quality: def.quality, term: .exclusive, acquired: s.date, refreshed: s.date)
        h.exclusive = true
        h.value = paid
        s.dataEco.holdings.append(h)
    }

    static func rivalWins(_ s: inout GameState, _ def: DatasetDef, lab: String, price: Double) {
        s.dataEco.rivalGains[lab, default: []].append(def.id)
        let name = CompetitorCatalog.def(lab).name
        Sim.news(&s, "\(name) buys \(def.name)", "Reportedly for about \(Fmt.money(price)). Expect it in their next models (capability +\(Fmt.trim(min(0.04, def.rivalValue), 3)) log-compute).",
                 .competitor)
    }

