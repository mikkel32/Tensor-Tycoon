import Foundation

/// The posts behind the Pulse, by story. Each line is "pool|text": the pool says who posts it — an anonymous persona
/// (insider, skeptic, joker, booster, dev, bench, finance, worried) or someone from the cast (lead: the lab's chief;
/// staff: its people; self: the person in the story; you: your own people; rival, analyst, reporter, investor, critic,
/// academic, official, regulator / deregulator (officials for or against rules), backer / opponent (of the bill in the
/// story), tester (officials who test models), colleague (someone at the place a person just joined), hypeman,
/// contrarian). A trailing + or − nudges the post's tone toward the lab it's about; "/BS" after the pool limits a line to
/// people whose voice is in those families (bold, careful, terse, skeptic, worried, numbers).
/// `{name's}` is a possessive. Some facts exist only to gate a line: {ifsafety} (a safety bill), {ifdereg} (a bill that
/// loosens rules), {ifsmall} / {ifbig} (the lab's size), {iffromlab} / {ifestablished} (a career move from a lab / to a lab
/// at least a year old) fill in as nothing, and a line that needs a missing one isn't used.
enum PulseBank {
    static let lines: [String: [String]] = {
        var all: [String: [String]] = [:]
        for part in [launches, money, world, milestones, careers, plays, ambient] { all.merge(part) { a, _ in a } }
        return all
    }()

